/**
 * Adaptive SOC - SAFE SYNTHETIC ATTACK SIMULATOR
 *
 * Generates ONLY synthetic SecurityEvent objects in-memory. Never performs
 * password guessing, never contacts a real authentication service, never
 * scans or attacks any real system. This is the sole source of "attack"
 * traffic in this build (see docs/LIMITATIONS.md for the Wazuh FILE-mode
 * note).
 */
const Simulator = (() => {
  const LAB_HOSTS = ['WIN-LABHOST-01'];
  const LAB_ACCOUNT = () => CONFIG.LAB_TARGET_ACCOUNT;

  function randomIp(pool) {
    return pool[Math.floor(Math.random() * pool.length)];
  }

  function genIpPool(count) {
    const pool = [];
    for (let i = 0; i < count; i++) {
      pool.push(`203.0.113.${10 + i}`); // TEST-NET-3, RFC5737 documentation-only range
    }
    return pool;
  }

  function buildEvent({ tOffsetMs, result, sourceIp, username, eventCode, logonType }) {
    const ts = new Date(Date.now() + tOffsetMs).toISOString();
    return {
      timestamp: ts,
      event_type: result === 'SUCCESS' ? 'AUTH_SUCCESS' : 'AUTH_FAILURE',
      source_ip: sourceIp,
      target_ip: '10.10.10.5',
      username,
      authentication_result: result,
      event_code: eventCode,
      logon_type: logonType || '3',
      hostname: LAB_HOSTS[0],
      source: 'SIMULATOR',
      raw_data: JSON.stringify({ synthetic: true, note: 'Generated by safe attack simulator, no real authentication attempt occurred.' }),
    };
  }

  /** NORMAL: a handful of successful logons, no failures. */
  function scenarioNormal() {
    const events = [];
    const users = ['jsmith', 'akumar', 'mlopez'];
    for (let i = 0; i < 6; i++) {
      events.push(buildEvent({
        tOffsetMs: i * 4000,
        result: 'SUCCESS',
        sourceIp: '10.10.10.20',
        username: users[i % users.length],
        eventCode: '4624',
      }));
    }
    return events;
  }

  /** LOW_FREQUENCY_FAILURE: a few scattered failures, single IP, low rate. */
  function scenarioLowFrequency() {
    const events = [];
    for (let i = 0; i < 4; i++) {
      events.push(buildEvent({
        tOffsetMs: i * 15000,
        result: 'FAILURE',
        sourceIp: '10.10.10.21',
        username: 'jsmith',
        eventCode: '4625',
      }));
    }
    events.push(buildEvent({ tOffsetMs: 60000, result: 'SUCCESS', sourceIp: '10.10.10.21', username: 'jsmith', eventCode: '4624' }));
    return events;
  }

  /** BRUTE_FORCE: many failures from ONE source IP against ONE account, high rate. */
  function scenarioBruteForce() {
    const events = [];
    const ip = '198.51.100.42'; // TEST-NET-2
    for (let i = 0; i < 22; i++) {
      events.push(buildEvent({
        tOffsetMs: i * 1500,
        result: 'FAILURE',
        sourceIp: ip,
        username: LAB_ACCOUNT(),
        eventCode: '4625',
      }));
    }
    return events;
  }

  /** ROTATING_SOURCE_ATTACK: 30 failures, 10 rotating IPs, same account, short window. */
  function scenarioRotatingSource() {
    const events = [];
    const pool = genIpPool(10);
    for (let i = 0; i < 30; i++) {
      events.push(buildEvent({
        tOffsetMs: i * 1200,
        result: 'FAILURE',
        sourceIp: randomIp(pool),
        username: LAB_ACCOUNT(),
        eventCode: '4625',
      }));
    }
    return events;
  }

  /**
   * PERSISTENT_ATTACK: rotating-source pattern that CONTINUES after
   * containment would normally apply — used to demonstrate escalation.
   * Returns { initial, followUp } event batches.
   */
  function scenarioPersistent() {
    const pool = genIpPool(14);
    const initial = [];
    for (let i = 0; i < 30; i++) {
      initial.push(buildEvent({
        tOffsetMs: i * 1000,
        result: 'FAILURE',
        sourceIp: randomIp(pool),
        username: LAB_ACCOUNT(),
        eventCode: '4625',
      }));
    }
    const followUp = [];
    for (let i = 0; i < 20; i++) {
      followUp.push(buildEvent({
        tOffsetMs: 40000 + i * 1100,
        result: 'FAILURE',
        sourceIp: randomIp(pool),
        username: LAB_ACCOUNT(),
        eventCode: '4625',
      }));
    }
    return { initial, followUp };
  }

  function generate(scenario) {
    switch (scenario) {
      case 'NORMAL': return { events: scenarioNormal() };
      case 'LOW_FREQUENCY_FAILURE': return { events: scenarioLowFrequency() };
      case 'BRUTE_FORCE': return { events: scenarioBruteForce() };
      case 'ROTATING_SOURCE_ATTACK': return { events: scenarioRotatingSource() };
      case 'PERSISTENT_ATTACK': {
        const { initial, followUp } = scenarioPersistent();
        return { events: initial, followUp };
      }
      default: throw new Error(`Unknown scenario: ${scenario}`);
    }
  }

  return { generate };
})();
