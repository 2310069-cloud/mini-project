<#
.SYNOPSIS
  ALLOWLISTED credential security script. Resets the password of ONLY
  the pre-configured authorized laboratory account, and ONLY when
  invoked by the deterministic credential security policy (never
  directly by AI output).

.DESCRIPTION
  - The backend/orchestrator must validate that -Account exactly matches
    the configured LAB_TARGET_ACCOUNT before ever invoking this script.
  - This script does NOT accept or construct arbitrary usernames from
    AI output; the caller is responsible for that validation, and this
    script re-validates against its own allowlist as a second gate.
  - In DRY_RUN mode, no real password is changed and no real credential
    is generated by this script — it returns a SIMULATED result only.
  - In LIVE mode, a cryptographically strong temporary password is
    generated LOCALLY by the calling orchestrator (never by this script,
    never by any AI) and passed in as a SecureString. This script never
    logs, echoes, or persists that value in plaintext.

.PARAMETER Account
  The account to reset. Must match the allowlisted lab account below.

.PARAMETER IncidentId
  Incident code for audit logging.

.PARAMETER TempPassword
  SecureString containing the new temporary password. Required only
  when -DryRun is $false. Never written to disk or logs.

.PARAMETER DryRun
  If $true (default), no real password is changed.
#>

param(
  [Parameter(Mandatory = $true)]
  [string]$Account,

  [Parameter(Mandatory = $true)]
  [ValidatePattern('^INC-\d{4}-\d{3,}$')]
  [string]$IncidentId,

  [Parameter(Mandatory = $false)]
  [System.Security.SecureString]$TempPassword,

  [Parameter(Mandatory = $false)]
  [bool]$DryRun = $true
)

$ErrorActionPreference = 'Stop'

# Second allowlist gate — must match the configured lab account exactly.
# Keep this in sync with LAB_TARGET_ACCOUNT in the application configuration.
$AllowedLabAccount = 'admin'

$logLine = "$(Get-Date -Format o) | INCIDENT=$IncidentId | ACTION=PASSWORD_RESET | ACCOUNT=$Account | MODE=$(if ($DryRun) {'DRY_RUN'} else {'LIVE'})"

if ($Account -ne $AllowedLabAccount) {
  Add-Content -Path "$PSScriptRoot\credential_audit.log" -Value "$logLine | REJECTED=account_not_allowlisted"
  Write-Output (@{ action = 'PASSWORD_RESET'; status = 'FAILED'; error = 'Account is not the configured authorized laboratory account.' } | ConvertTo-Json -Compress)
  exit 1
}

try {
  if ($DryRun) {
    Write-Output (@{ action = 'PASSWORD_RESET'; mode = 'DRY_RUN'; status = 'SIMULATED'; account = $Account } | ConvertTo-Json -Compress)
  }
  else {
    if (-not $TempPassword) {
      throw 'TempPassword is required for a LIVE password reset.'
    }
    Set-LocalUser -Name $Account -Password $TempPassword
    Set-LocalUser -Name $Account -PasswordNeverExpires $false
    # Force change at next logon where supported:
    net user $Account /logonpasswordchg:yes | Out-Null

    Write-Output (@{ action = 'PASSWORD_RESET'; mode = 'LIVE'; status = 'COMPLETED'; account = $Account; requires_password_change = $true } | ConvertTo-Json -Compress)
  }
  # NOTE: the plaintext password is NEVER written to this log or any log.
  Add-Content -Path "$PSScriptRoot\credential_audit.log" -Value $logLine
}
catch {
  Add-Content -Path "$PSScriptRoot\credential_audit.log" -Value "$logLine | ERROR=$($_.Exception.Message)"
  Write-Output (@{ action = 'PASSWORD_RESET'; status = 'FAILED'; error = $_.Exception.Message } | ConvertTo-Json -Compress)
  exit 1
}
